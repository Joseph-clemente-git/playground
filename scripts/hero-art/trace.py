"""
Printer-style reproduction of the Word Warrior hero: scan the reference,
separate it into colour plates, trace each plate to vector, and stack them in
register. Writes src/games/word-warrior/heroPlates.ts.

    python3 -m venv .venv && .venv/bin/pip install opencv-python-headless
    .venv/bin/python scripts/hero-art/trace.py
"""
import cv2, numpy as np, sys
import os
HERE = os.path.dirname(os.path.abspath(__file__))
K = int(sys.argv[1]) if len(sys.argv) > 1 else 24
S = 800                                  # working resolution; output space is 400
src = cv2.imread(os.path.join(HERE, 'reference.png'))
up = cv2.resize(src, (S, S), interpolation=cv2.INTER_LANCZOS4)
up = cv2.bilateralFilter(up, 7, 22, 7)

# 1. Separate figure from paper: flood the near-white background in from the edges.
gray = cv2.cvtColor(up, cv2.COLOR_BGR2GRAY)
sat = cv2.cvtColor(up, cv2.COLOR_BGR2HSV)[..., 1]
paper = ((gray > 238) & (sat < 22)).astype(np.uint8)
flood = paper.copy()
ff = np.zeros((S + 2, S + 2), np.uint8)
for seed in [(0, 0), (S - 1, 0), (0, S - 1), (S - 1, S - 1)]:
    if flood[seed[1], seed[0]] == 1:
        cv2.floodFill(flood, ff, seed, 2)
fg = (flood != 2).astype(np.uint8)
fg = cv2.morphologyEx(fg, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))
# Plates sit just inside the silhouette, so the soft anti-aliased edge becomes a clean ink outline.
inner = cv2.erode(fg, np.ones((5, 5), np.uint8))

# 2. Colour separation: k-means in Lab over the figure only.
lab = cv2.cvtColor(up, cv2.COLOR_BGR2LAB).astype(np.float32)
lab[..., 1:] *= 1.6
pts = lab[inner > 0]
crit = (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 60, 0.3)
_, lbl, centers = cv2.kmeans(pts, K, None, crit, 4, cv2.KMEANS_PP_CENTERS)
labels = np.full((S, S), -1, np.int32)
labels[inner > 0] = lbl[:, 0]

# 3. Mode filter: each pixel takes the plate most common around it, removing speckle.
votes = np.stack([cv2.boxFilter((labels == k).astype(np.float32), -1, (9, 9)) for k in range(K)])
labels = np.where(inner > 0, votes.argmax(0), -1)

centers[:, 1:] /= 1.6
rgb = cv2.cvtColor(centers.reshape(1, K, 3).astype(np.uint8), cv2.COLOR_LAB2RGB)[0]
light = centers[:, 0]
order = np.argsort(-light)               # light plates first, ink last on top

def path_for(mask, eps=1.5, min_area=40):
    cnts, _ = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    parts = []
    for c in cnts:
        if cv2.contourArea(c) < min_area:
            continue
        p = cv2.approxPolyDP(c, eps, True)[:, 0].astype(np.float32) / (S / 400)
        if len(p) < 3:
            continue
        mids = (p + np.roll(p, -1, 0)) / 2
        d = f'M{mids[-1][0]:.1f} {mids[-1][1]:.1f}'
        for q, m in zip(p, mids):
            d += f'Q{q[0]:.0f} {q[1]:.0f} {m[0]:.1f} {m[1]:.1f}'
        parts.append(d + 'Z')
    return ''.join(parts)

layers = []
# Registration base: the whole silhouette in the darkest ink, so no paper shows between plates.
ink = int(np.argmin(light))
layers.append(('#%02x%02x%02x' % tuple(rgb[ink]), path_for(fg)))
for k in order:
    if k == ink:
        continue
    m = (labels == k).astype(np.uint8)
    m = cv2.dilate(m, np.ones((4, 4), np.uint8))   # slight overlap so plates register without seams
    d = path_for(m)
    if d:
        layers.append(('#%02x%02x%02x' % tuple(rgb[k]), d))
# Detail plates, like a printer's black (K) plate: line work and highlights traced
# straight from the scan without smoothing, so faces and edges stay crisp.
sharp = cv2.resize(src, (S, S), interpolation=cv2.INTER_CUBIC)
sg = cv2.cvtColor(sharp, cv2.COLOR_BGR2GRAY)
ssat = cv2.cvtColor(sharp, cv2.COLOR_BGR2HSV)[..., 1]
hi = ((sg > 222) & (ssat < 60) & (inner > 0)).astype(np.uint8)
hi = cv2.morphologyEx(hi, cv2.MORPH_OPEN, np.ones((2, 2), np.uint8))
d = path_for(hi, 0.8, 10)
if d:
    layers.append(('#fffbf0', d))
# Black-hat keeps thin dark strokes and small dark spots (pupils), not big dark areas.
blackhat = cv2.morphologyEx(sg, cv2.MORPH_BLACKHAT, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (17, 17)))
kline = ((blackhat > 34) & (sg < 110) & (fg > 0)).astype(np.uint8)
kline = cv2.morphologyEx(kline, cv2.MORPH_OPEN, np.ones((2, 2), np.uint8))
# A softer line plate for mid-brown strokes: the smile, nose, eyelids and lock separations.
mid = ((blackhat > 16) & (sg < 175) & (fg > 0)).astype(np.uint8) & (1 - kline)
mid = cv2.morphologyEx(mid, cv2.MORPH_OPEN, np.ones((2, 2), np.uint8))
d = path_for(mid, 1.0, 16)
if d:
    layers.append(('#8a4524', d))
d = path_for(kline, 0.8, 8)
if d:
    layers.append(('#2a160c', d))
ts = ['// Generated by tracing the hero reference into stacked colour plates. Do not edit by hand.',
      'export const HERO_PLATES: [string, string][] = [']
ts += [f"  ['{c}', '{d}']," for c, d in layers]
ts.append(']\n')
open(sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '../../src/games/word-warrior/heroPlates.ts'), 'w').write('\n'.join(ts))
print('plates', len(layers), 'bytes', sum(len(d) for _, d in layers))
